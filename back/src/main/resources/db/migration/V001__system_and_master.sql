CREATE TABLE sys_department (
 id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL,
 parent_id BIGINT NULL, type VARCHAR(32) NOT NULL DEFAULT 'CLINICAL', enabled BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY (parent_id) REFERENCES sys_department(id)
);
CREATE TABLE sys_location (
 id BIGINT PRIMARY KEY, department_id BIGINT NOT NULL, code VARCHAR(64) NOT NULL UNIQUE,
 name VARCHAR(200) NOT NULL, type VARCHAR(32) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 FOREIGN KEY (department_id) REFERENCES sys_department(id)
);
CREATE TABLE sys_user (
 id BIGINT PRIMARY KEY, username VARCHAR(64) NOT NULL UNIQUE, password_hash VARCHAR(200) NOT NULL,
 display_name VARCHAR(100) NOT NULL, department_id BIGINT NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), FOREIGN KEY (department_id) REFERENCES sys_department(id)
);
CREATE TABLE sys_role (id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL);
CREATE TABLE sys_permission (id BIGINT PRIMARY KEY, code VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL);
CREATE TABLE sys_user_role (user_id BIGINT NOT NULL, role_id BIGINT NOT NULL, PRIMARY KEY(user_id,role_id), FOREIGN KEY(user_id) REFERENCES sys_user(id), FOREIGN KEY(role_id) REFERENCES sys_role(id));
CREATE TABLE sys_role_permission (role_id BIGINT NOT NULL, permission_id BIGINT NOT NULL, PRIMARY KEY(role_id,permission_id), FOREIGN KEY(role_id) REFERENCES sys_role(id), FOREIGN KEY(permission_id) REFERENCES sys_permission(id));
CREATE TABLE sys_user_scope (user_id BIGINT NOT NULL, location_id BIGINT NOT NULL, PRIMARY KEY(user_id,location_id), FOREIGN KEY(user_id) REFERENCES sys_user(id), FOREIGN KEY(location_id) REFERENCES sys_location(id));
CREATE TABLE sys_audit_log (
 id BIGINT PRIMARY KEY, user_id BIGINT NOT NULL, action VARCHAR(64) NOT NULL, source_type VARCHAR(64) NOT NULL,
 source_id BIGINT NULL, reason VARCHAR(500) NULL, occurred_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX ix_audit_source(source_type,source_id,occurred_at), FOREIGN KEY(user_id) REFERENCES sys_user(id)
);
CREATE TABLE sys_document_action (
 id BIGINT PRIMARY KEY, source_type VARCHAR(64) NOT NULL, source_id BIGINT NOT NULL,
 from_status VARCHAR(32), to_status VARCHAR(32) NOT NULL, action VARCHAR(64) NOT NULL,
 operator_id BIGINT NOT NULL, reason VARCHAR(500), occurred_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX ix_action(source_type,source_id), FOREIGN KEY(operator_id) REFERENCES sys_user(id)
);
CREATE TABLE sys_config (config_key VARCHAR(100) PRIMARY KEY, config_value VARCHAR(1000) NOT NULL);
CREATE TABLE sys_idempotency (
 id BIGINT PRIMARY KEY, user_id BIGINT NOT NULL, route_key VARCHAR(120) NOT NULL, request_key VARCHAR(100) NOT NULL,
 request_hash VARCHAR(64) NOT NULL, result_json JSON NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE(user_id,route_key,request_key)
);
CREATE TABLE SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY, SESSION_ID CHAR(36) NOT NULL, CREATION_TIME BIGINT NOT NULL,
 LAST_ACCESS_TIME BIGINT NOT NULL, MAX_INACTIVE_INTERVAL INT NOT NULL, EXPIRY_TIME BIGINT NOT NULL, PRINCIPAL_NAME VARCHAR(100),
 UNIQUE KEY SPRING_SESSION_IX1 (SESSION_ID), INDEX SPRING_SESSION_IX2 (EXPIRY_TIME), INDEX SPRING_SESSION_IX3 (PRINCIPAL_NAME)
);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL, ATTRIBUTE_NAME VARCHAR(200) NOT NULL, ATTRIBUTE_BYTES BLOB NOT NULL,
 PRIMARY KEY(SESSION_PRIMARY_ID,ATTRIBUTE_NAME), FOREIGN KEY(SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
CREATE TABLE md_unit (id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL, dimension VARCHAR(32) NOT NULL DEFAULT 'COUNT');
CREATE TABLE md_manufacturer (id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL, contact VARCHAR(200), enabled BOOLEAN NOT NULL DEFAULT TRUE);
CREATE TABLE md_supplier (id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL, contact VARCHAR(200), license_no VARCHAR(100), enabled BOOLEAN NOT NULL DEFAULT TRUE);
CREATE TABLE md_item (
 id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL, specification VARCHAR(200) NOT NULL,
 item_type VARCHAR(32) NOT NULL, base_unit_id BIGINT NOT NULL, quantity_scale INT NOT NULL DEFAULT 0, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), version INT NOT NULL DEFAULT 0, FOREIGN KEY(base_unit_id) REFERENCES md_unit(id),
 CHECK(quantity_scale BETWEEN 0 AND 6)
);
CREATE TABLE md_item_unit (
 id BIGINT PRIMARY KEY, item_id BIGINT NOT NULL, unit_id BIGINT NOT NULL, factor_to_base DECIMAL(18,6) NOT NULL,
 UNIQUE(item_id,unit_id), FOREIGN KEY(item_id) REFERENCES md_item(id), FOREIGN KEY(unit_id) REFERENCES md_unit(id), CHECK(factor_to_base>0)
);
CREATE TABLE md_drug (
 id BIGINT PRIMARY KEY, item_id BIGINT NOT NULL UNIQUE, generic_name VARCHAR(200) NOT NULL, trade_name VARCHAR(200),
 manufacturer_id BIGINT NOT NULL, dosage_form VARCHAR(64) NOT NULL, category VARCHAR(64) NOT NULL,
 insurance_code VARCHAR(100), insurance_category VARCHAR(32) NOT NULL DEFAULT 'SELF_PAY', prescription_required BOOLEAN NOT NULL DEFAULT TRUE,
 control_level VARCHAR(32) NOT NULL DEFAULT 'NORMAL', imported BOOLEAN NOT NULL DEFAULT FALSE,
 in_house BOOLEAN NOT NULL DEFAULT FALSE, self_pay BOOLEAN NOT NULL DEFAULT FALSE, valuable BOOLEAN NOT NULL DEFAULT FALSE,
 retail_price DECIMAL(18,6) NOT NULL DEFAULT 0, price_version INT NOT NULL DEFAULT 0,
 FOREIGN KEY(item_id) REFERENCES md_item(id), FOREIGN KEY(manufacturer_id) REFERENCES md_manufacturer(id), CHECK(retail_price>=0)
);
CREATE TABLE md_drug_alias (id BIGINT PRIMARY KEY, drug_id BIGINT NOT NULL, alias VARCHAR(200) NOT NULL, UNIQUE(drug_id,alias), FOREIGN KEY(drug_id) REFERENCES md_drug(id));
CREATE TABLE md_ingredient (id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL);
CREATE TABLE md_drug_ingredient (
 id BIGINT PRIMARY KEY, drug_id BIGINT NOT NULL, ingredient_id BIGINT NOT NULL, strength_amount DECIMAL(18,6) NOT NULL,
 strength_unit VARCHAR(32) NOT NULL DEFAULT 'mg', UNIQUE(drug_id,ingredient_id), FOREIGN KEY(drug_id) REFERENCES md_drug(id), FOREIGN KEY(ingredient_id) REFERENCES md_ingredient(id)
);
CREATE TABLE md_location_item (
 id BIGINT PRIMARY KEY, location_id BIGINT NOT NULL, item_id BIGINT NOT NULL, min_qty DECIMAL(18,6) NOT NULL DEFAULT 0,
 target_qty DECIMAL(18,6) NOT NULL DEFAULT 100, expiry_warn_days INT NOT NULL DEFAULT 90,
 UNIQUE(location_id,item_id), FOREIGN KEY(location_id) REFERENCES sys_location(id), FOREIGN KEY(item_id) REFERENCES md_item(id)
);
CREATE TABLE md_diagnosis (id BIGINT PRIMARY KEY, code VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL);
